// Replaces `loans` with a single, general-purpose ledger of money owed between two
// SPECIFIC partners — because this workshop has no central cash fund. Every balance,
// whether it came from a manual loan or from one partner holding more cash than their
// profit share entitles them to, is "partner A owes partner B this amount" and nothing
// else. Modeling both cases the same way means settlement, history, and "remove from the
// active list once settled" logic is written once instead of twice (previously split
// between `loans` and the opening/closing balance fields on `monthly_balances`).
//
// type = 'loan'              -> a manual loan between two partners (what `loans` used to hold)
// type = 'profit_settlement' -> a transfer needed to equalize that month's profit split,
//                                generated by POST /api/reports/monthly/:year/:month/settlements
//                                (period_year/period_month identify which month it's for,
//                                so that generation step is idempotent)

